const LangContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState(() => localStorage.getItem("ne-lang") || "en");
  useEffect(() => {
    localStorage.setItem("ne-lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);
  const t = (key) => dict[lang][key] ?? dict.en[key] ?? key;
  const pick = (obj) => (obj && typeof obj === "object" ? obj[lang] ?? obj.en : obj);
  return <LangContext.Provider value={{ lang, setLang, t, pick }}>{children}</LangContext.Provider>;
};

export const useLang = () => useContext(LangContext);
